const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');

test('dashboard exposes the upgraded management surfaces with safe DOM patterns', async () => {
  const root = path.join(__dirname, '..');
  const [html, app] = await Promise.all([
    fs.readFile(path.join(root, 'public', 'index.html'), 'utf8'),
    fs.readFile(path.join(root, 'public', 'app.js'), 'utf8')
  ]);
  for (const id of ['invite-list', 'setting-panel-exposure', 'dashboard-url-form']) assert.match(html, new RegExp(`id="${id}"`));
  for (const id of ['overview-monitor-select', 'overview-monitor-cpu', 'overview-monitor-memory', 'overview-monitor-players']) assert.match(html, new RegExp(`id="${id}"`));
  assert.match(html, /id="modpack-create-form"/);
  assert.match(html, /icon-refresh-cw/);
  assert.match(html, /id="theme-toggle" class="icon-button secondary"/);
  assert.match(html, /id="logout" class="icon-button secondary"/);
  assert.match(html, /rel="icon" type="image\/png" href="\/assets\/logo\.png\?v=3"/);
  assert.match(html, /id="sidebar-toggle-zone" class="sidebar-toggle-zone"/);
  assert.match(html, /id="sidebar-close" class="sidebar-close icon-button"/);
  assert.match(html, /id="refresh"[\s\S]*id="theme-toggle"[\s\S]*id="logout"/);
  assert.doesNotMatch(html, /identity-name|identity-role|identity-avatar|Toggle theme/);
  assert.doesNotMatch(html, /id="access-summary"/);
  assert.match(html, /lucide-icon icon-layout-dashboard/);
  assert.match(html, /id="audit-filter"/);
  assert.match(html, /id="ssh-key-form"/);
  assert.match(html, /id="member-edit-dialog"/);
  assert.match(html, /id="member-edit-form"/);
  assert.match(html, /name="name" required maxlength="48" placeholder="Steve"/);
  assert.doesNotMatch(html, /id="global-state"|Everything needed to run Minecraft/);
  assert.doesNotMatch(html, /id="page-eyebrow"|>Infrastructure</);
  assert.doesNotMatch(html, /Friday survival|Automatic port allocation|Persistent storage|class="panel guide-card"/);
  for (const className of ['installed-content', 'players', 'uptime']) assert.match(html, new RegExp(`class="[^"]*${className}`));
  assert.match(html, /role="tablist"/);
  assert.match(html, /role="tabpanel"/);
  assert.match(app, /result\?\.editable !== false/);
  assert.match(app, /loadInstalledContent/);
  assert.match(app, /loadInvites/);
  assert.match(app, /inviteDashboardUrl/);
  assert.match(app, /localhost tunnel links only work for you/);
  assert.match(app, /new URLSearchParams\(\{ query, kind, limit: '24' \}\)/);
  assert.match(app, /if \(provider === 'hangar'\) params\.set\('loader', providerLoader\(server\)\)/);
  assert.match(app, /Exact compatibility is checked when you choose a version/);
  assert.match(app, /function modpackRuntimes/);
  assert.match(app, /Create server \+ install pack/);
  assert.match(app, /createServerFromModpack/);
  assert.match(app, /catalog-project-link/);
  assert.match(app, /if \(status\) \$\('\.server-status-dot', workspace\)\.classList\.add\(status\)/);
  assert.match(app, /event\.actor\?\.displayName/);
  assert.doesNotMatch(app, /initializePointerEffect|pointer-halo/);
  assert.match(app, /new URLSearchParams\(\{ limit: '25' \}\)/);
  assert.match(app, /Create a matching server from a modpack/);
  assert.match(html, /data-action="export-backup"/);
  assert.match(html, /data-action="import-backup"/);
  assert.match(app, /function exportBackup/);
  assert.match(app, /function importBackup/);
  assert.match(html, /value="start">Since server start/);
  assert.match(html, /value="custom">Custom time window/);
  assert.match(html, /data-console-filter="give"/);
  assert.match(html, /data-console-filter="gamemode"/);
  assert.doesNotMatch(html, /Admin command shortcuts|data-command-template/);
  assert.match(html, /data-console-filter="operator"/);
  assert.match(app, /function renderConsoleLogs/);
  assert.match(app, /function renderOverviewMonitor/);
  assert.match(app, /member-presence/);
  assert.match(app, /function openMemberEdit/);
  assert.match(app, /function saveMemberEdit/);
  assert.doesNotMatch(app, /Role: member, operator, or viewer/);
  assert.match(app, /New dashboard key/);
  assert.match(app, /Re-enable/);
  assert.match(app, /This cannot be undone/);
  assert.match(app, /function emptyState\(container, title, message\)/);
  assert.doesNotMatch(app, /if \(icon\) wrapper\.append/);
  assert.match(app, /function upgradeRefreshButtons/);
  assert.match(app, /function refreshOverviewMonitor/);
  assert.doesNotMatch(app, /refreshed with the dashboard/);
  assert.match(app, /function setSidebarCollapsed/);
  assert.match(app, /consoleLogFilters/);
  assert.doesNotMatch(app, /limit: '50'/);
  assert.doesNotMatch(app, /innerHTML|insertAdjacentHTML|\beval\s*\(/);
  assert.doesNotMatch(app, /\/modrinth(?:\/modpack)?[`'"?]/);
});
